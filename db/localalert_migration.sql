  ADD COLUMN current_municipality_id INTEGER CONSTRAINT fk_user_current_municipality
             REFERENCES municipalities(municipality_id) ON DELETE SET NULL,
  ADD COLUMN last_location_at       TIMESTAMP,
  ADD COLUMN pin_hash               TEXT,
  ADD COLUMN push_token             TEXT;

CREATE INDEX idx_user_municipality         ON users (municipality_id);
CREATE INDEX idx_user_current_municipality ON users (current_municipality_id);

-- 5. alerts: link to profile, municipality, escalation, resolution
ALTER TABLE alerts
  ADD COLUMN member_id         UUID CONSTRAINT fk_alert_member
             REFERENCES family_members(member_id) ON DELETE SET NULL,
  ADD COLUMN municipality_id   INTEGER CONSTRAINT fk_alert_municipality
             REFERENCES municipalities(municipality_id) ON DELETE SET NULL,
  ADD COLUMN escalation_level  SMALLINT NOT NULL DEFAULT 1
             CONSTRAINT chk_alert_level CHECK (escalation_level BETWEEN 1 AND 4),
  ADD COLUMN last_escalated_at TIMESTAMP,
  ADD COLUMN resolved_at       TIMESTAMP;

UPDATE alerts SET last_escalated_at = COALESCE(created_at, CURRENT_TIMESTAMP);
UPDATE alerts SET resolved_at = COALESCE(updated_at, CURRENT_TIMESTAMP)
 WHERE lower(status) = 'resolved' AND resolved_at IS NULL;

ALTER TABLE alerts
  ALTER COLUMN last_escalated_at SET DEFAULT CURRENT_TIMESTAMP,
  ALTER COLUMN last_escalated_at SET NOT NULL;

ALTER TABLE alerts ADD CONSTRAINT chk_alert_status
  CHECK (status IS NULL OR lower(status) IN ('active', 'still_missing', 'resolved')) NOT VALID;

CREATE INDEX idx_alert_escalation   ON alerts (status, escalation_level, last_escalated_at);
CREATE INDEX idx_alert_municipality ON alerts (municipality_id);

