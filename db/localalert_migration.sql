-- 1. New table: municipalities
CREATE TABLE municipalities (
  municipality_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  municipality_code  VARCHAR(20)  NOT NULL UNIQUE,
  municipality_name  VARCHAR(150) NOT NULL,
  municipality_type  VARCHAR(20)  NOT NULL DEFAULT 'local'
                     CONSTRAINT chk_muni_type CHECK (municipality_type IN ('metro', 'local')),
  province           VARCHAR(100) NOT NULL,
  centroid_latitude  NUMERIC(10,8),
  centroid_longitude NUMERIC(11,8),
  created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. New table: municipality_neighbours (stored in BOTH directions)
CREATE TABLE municipality_neighbours (
  relationship_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  municipality_id           INTEGER NOT NULL REFERENCES municipalities(municipality_id) ON DELETE CASCADE,
  neighbour_municipality_id INTEGER NOT NULL REFERENCES municipalities(municipality_id) ON DELETE CASCADE,
  CONSTRAINT uq_muni_neighbour UNIQUE (municipality_id, neighbour_municipality_id),
  CONSTRAINT chk_muni_not_self CHECK (municipality_id <> neighbour_municipality_id)
);

-- Helper: add_neighbour_pair('TSH','JHB') inserts A->B and B->A
CREATE OR REPLACE FUNCTION add_neighbour_pair(code_a TEXT, code_b TEXT) RETURNS void AS $$
  INSERT INTO municipality_neighbours (municipality_id, neighbour_municipality_id)
  SELECT a.municipality_id, b.municipality_id
    FROM municipalities a, municipalities b
   WHERE a.municipality_code = code_a AND b.municipality_code = code_b
  UNION ALL
  SELECT b.municipality_id, a.municipality_id
    FROM municipalities a, municipalities b
   WHERE a.municipality_code = code_a AND b.municipality_code = code_b
  ON CONFLICT DO NOTHING;
$$ LANGUAGE sql;

-- 3. New tables: Family Link
CREATE TABLE family_groups (
  group_id      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  admin_user_id UUID NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  group_name    VARCHAR(100) NOT NULL,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE family_members (
  member_id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  group_id             UUID NOT NULL REFERENCES family_groups(group_id) ON DELETE CASCADE,
  user_id              UUID REFERENCES users(user_id) ON DELETE SET NULL,
  full_name            VARCHAR(100) NOT NULL,
  date_of_birth        DATE NOT NULL,
  gender               VARCHAR(10) NOT NULL,
  physical_description TEXT NOT NULL,
  photo_url            TEXT,
  id_document_url      TEXT,
  verification_status  VARCHAR(20) NOT NULL DEFAULT 'pending'
                       CONSTRAINT chk_member_verif CHECK (verification_status IN ('pending', 'verified')),
  created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_member_group_user UNIQUE (group_id, user_id),
  CONSTRAINT chk_verified_needs_id CHECK (verification_status <> 'verified' OR id_document_url IS NOT NULL)
);

CREATE TABLE family_links (
  link_id   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  group_id  UUID NOT NULL REFERENCES family_groups(group_id) ON DELETE CASCADE,
  user_id   UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  linked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_link_group_user UNIQUE (group_id, user_id)
);

CREATE TABLE family_invitations (
  invitation_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  group_id      UUID NOT NULL REFERENCES family_groups(group_id) ON DELETE CASCADE,
  invited_by    UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  token_hash    TEXT NOT NULL UNIQUE,
  method        VARCHAR(10) NOT NULL
                CONSTRAINT chk_invite_method CHECK (method IN ('invite', 'qr')),
  invite_email  VARCHAR(100),
  invite_phone  VARCHAR(20),
  status        VARCHAR(10) NOT NULL DEFAULT 'pending'
                CONSTRAINT chk_invite_status CHECK (status IN ('pending', 'accepted', 'expired', 'revoked')),
  expires_at    TIMESTAMP NOT NULL,
  accepted_by   UUID REFERENCES users(user_id) ON DELETE SET NULL,
  accepted_at   TIMESTAMP,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_invite_group ON family_invitations (group_id, status);

-- 4. users: municipality, language, PIN, push token
